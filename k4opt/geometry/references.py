"""The target reference grammar.

A *target reference* names exactly one XML attribute in a geometry description.
References are generated by discovery (see :mod:`k4opt.geometry.discovery`); users copy
them rather than author XPath. The grammar is deliberately narrow::

    reference = "constants." NAME
              | anchor { "." step } "." ATTR
    anchor    = NAME                      ; element carrying name="NAME"
              | TAG "[name=" VALUE "]"    ; tag-qualified named element
              | TAG                       ; the document root element
    step      = TAG
              | TAG "[name=" VALUE "]"
              | TAG "[id=" VALUE "]"
              | TAG "[" INDEX "]"         ; 1-based position among same-tag siblings
    NAME, TAG, ATTR = [A-Za-z_][A-Za-z0-9_-]*
    VALUE           = [A-Za-z0-9_.+-]+
    INDEX           = positive integer

``constants.NAME`` addresses the ``value`` attribute of ``<constant name="NAME">``.
Whether a bare first token is an element name or the root tag is decided by the
catalog, not by the parser: resolution is an exact lookup of the canonical text.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Literal

from k4opt.geometry.errors import InvalidTargetError

NAME_PATTERN = r"[A-Za-z_][A-Za-z0-9_\-]*"
VALUE_PATTERN = r"[A-Za-z0-9_.+\-]+"

_NAME_RE = re.compile(rf"{NAME_PATTERN}\Z")
_VALUE_RE = re.compile(rf"{VALUE_PATTERN}\Z")
_SEGMENT_RE = re.compile(
    rf"(?P<tag>{NAME_PATTERN})"
    rf"(?:\[(?:(?P<key>name|id)=(?P<value>{VALUE_PATTERN})|(?P<index>[1-9][0-9]*))\])?\Z"
)

CONSTANTS_PREFIX = "constants"

QualifierKey = Literal["name", "id", "index"]


def is_name(text: str | None) -> bool:
    """Return True if ``text`` is usable as a bare NAME/TAG/ATTR token."""
    return text is not None and _NAME_RE.match(text) is not None


def is_value(text: str | None) -> bool:
    """Return True if ``text`` is usable as a qualifier VALUE token."""
    return text is not None and _VALUE_RE.match(text) is not None


@dataclass(frozen=True, slots=True)
class Step:
    """One path segment: a tag with an optional ``name``/``id``/index qualifier."""

    tag: str
    key: QualifierKey | None = None
    value: str | None = None

    @property
    def order_sensitive(self) -> bool:
        return self.key == "index"

    def __str__(self) -> str:
        if self.key is None:
            return self.tag
        if self.key == "index":
            return f"{self.tag}[{self.value}]"
        return f"{self.tag}[{self.key}={self.value}]"


@dataclass(frozen=True, slots=True)
class ParameterReference:
    """A parsed target reference.

    ``kind`` is ``"constant"`` for ``constants.NAME`` and ``"path"`` otherwise.
    For path references ``segments`` holds the anchor followed by the steps, and
    ``attribute`` is the final XML attribute name. ``text`` is the canonical
    spelling used for catalog lookups.
    """

    kind: Literal["constant", "path"]
    segments: tuple[Step, ...]
    attribute: str

    @property
    def text(self) -> str:
        if self.kind == "constant":
            return f"{CONSTANTS_PREFIX}.{self.attribute}"
        return ".".join([*(str(s) for s in self.segments), self.attribute])

    @property
    def order_sensitive(self) -> bool:
        return any(s.order_sensitive for s in self.segments)

    def __str__(self) -> str:
        return self.text


def _split_segments(text: str) -> list[str]:
    """Split on ``.`` outside of ``[...]`` qualifiers."""
    parts: list[str] = []
    depth = 0
    current: list[str] = []
    for ch in text:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth < 0:
                raise InvalidTargetError(f"invalid target {text!r}: unbalanced ']'")
        if ch == "." and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    if depth != 0:
        raise InvalidTargetError(f"invalid target {text!r}: unbalanced '['")
    parts.append("".join(current))
    return parts


def parse_reference(text: str) -> ParameterReference:
    """Parse ``text`` into a :class:`ParameterReference` or raise :class:`InvalidTargetError`."""
    if not isinstance(text, str):
        raise InvalidTargetError(f"target must be a string, got {type(text).__name__}")
    if text != text.strip() or not text:
        raise InvalidTargetError(
            f"invalid target {text!r}: must be non-empty without surrounding whitespace"
        )
    parts = _split_segments(text)
    if len(parts) < 2:
        raise InvalidTargetError(
            f"invalid target {text!r}: expected at least '<anchor>.<attribute>' "
            "or 'constants.<name>'"
        )
    if parts[0] == CONSTANTS_PREFIX:
        if len(parts) != 2 or not is_name(parts[1]):
            raise InvalidTargetError(
                f"invalid target {text!r}: constant references have the form 'constants.<name>'"
            )
        return ParameterReference(kind="constant", segments=(), attribute=parts[1])

    attribute = parts[-1]
    if not is_name(attribute):
        raise InvalidTargetError(
            f"invalid target {text!r}: {attribute!r} is not a valid attribute name"
        )
    segments: list[Step] = []
    for i, part in enumerate(parts[:-1]):
        match = _SEGMENT_RE.match(part)
        if match is None:
            raise InvalidTargetError(f"invalid target {text!r}: segment {part!r} is malformed")
        if match.group("index") is not None:
            if i == 0:
                raise InvalidTargetError(
                    f"invalid target {text!r}: the first segment cannot carry a positional index"
                )
            segments.append(Step(match.group("tag"), "index", match.group("index")))
        elif match.group("key") is not None:
            key = match.group("key")
            if i == 0 and key != "name":
                raise InvalidTargetError(
                    f"invalid target {text!r}: the first segment may only be qualified "
                    "by [name=...]"
                )
            segments.append(Step(match.group("tag"), key, match.group("value")))  # type: ignore[arg-type]
        else:
            segments.append(Step(match.group("tag")))
    return ParameterReference(kind="path", segments=tuple(segments), attribute=attribute)
